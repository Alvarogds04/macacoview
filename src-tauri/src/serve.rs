#[cfg(test)]
mod tests {
    use super::*;
    use std::io::{Read as _, Write as _};
    use std::net::TcpStream;
    use std::time::Duration;

    /// Start the real sampling loop on an ephemeral port, as a real client
    /// would see it.
    fn spawn_test_server() -> SocketAddr {
        let state = start_sampling_loop();
        let (addr, _handle) = spawn_server(0, state).expect("server should bind to port 0");
        addr
    }

    fn send_request(addr: SocketAddr, request: &str) -> String {
        let mut stream =
            TcpStream::connect(addr).expect("client should connect to the test server");
        stream
            .set_read_timeout(Some(Duration::from_secs(5)))
            .expect("read timeout should apply");
        stream
            .write_all(request.as_bytes())
            .expect("request should be written");
        let mut response = String::new();
        stream
            .read_to_string(&mut response)
            .expect("response should be readable until close");
        response
    }

    fn get(addr: SocketAddr, path: &str) -> String {
        send_request(
            addr,
            &format!("GET {path} HTTP/1.1\r\nHost: localhost\r\nConnection: close\r\n\r\n"),
        )
    }

    #[test]
    fn api_state_matches_get_state_shape() {
        let addr = spawn_test_server();
        let response = get(addr, "/api/state");
        assert!(response.starts_with("HTTP/1.1 200 OK\r\n"), "got: {response}");
        assert!(response.contains("Content-Type: application/json"));

        let body = response
            .split_once("\r\n\r\n")
            .expect("headers should be separated from the body")
            .1;
        let json: serde_json::Value =
            serde_json::from_str(body).expect("body should be valid JSON");
        let keys = json
            .as_object()
            .expect("JSON body should be an object");
        // The contract: exactly the fields of `GetState`.
        assert_eq!(keys.len(), 2, "GetState must have exactly two keys");
        assert!(keys.contains_key("snapshot"));
        assert!(keys.contains_key("history"));
        assert!(
            keys["snapshot"].is_null() || keys["snapshot"].is_object(),
            "snapshot is Option<FullSnapshot>"
        );
        assert!(keys["history"].is_array(), "history is Vec<HistorySample>");
    }

    #[test]
    fn unknown_paths_return_404() {
        let addr = spawn_test_server();
        for path in ["/nope", "/api", "/api/", "/API/STATE", "/missing-forever.txt"] {
            let response = get(addr, path);
            assert!(
                response.starts_with("HTTP/1.1 404 Not Found\r\n"),
                "{path} should be 404, got: {response}"
            );
        }
    }

    #[test]
    fn path_traversals_are_rejected() {
        let addr = spawn_test_server();
        // Raw, percent-encoded and mixed traversals: all must fall through to
        // 404 because assets are matched exactly, never resolved on disk.
        for path in [
            "/../Cargo.toml",
            "/%2e%2e/Cargo.toml",
            "/..%2fCargo.toml",
            "/api/../Cargo.toml",
            "/../../etc/passwd",
        ] {
            let response = get(addr, path);
            assert!(
                response.starts_with("HTTP/1.1 404 Not Found\r\n"),
                "{path} should be 404, got: {response}"
            );
            assert!(
                !response.contains("[package]"),
                "{path} must never leak a source file"
            );
        }
    }

    #[test]
    fn root_serves_placeholder_or_embedded_frontend() {
        let addr = spawn_test_server();
        let response = get(addr, "/");
        assert!(response.starts_with("HTTP/1.1 200 OK\r\n"), "got: {response}");
        if ASSETS.is_empty() {
            // dist/ was not present at build time: the placeholder explains it.
            assert!(response.contains("Content-Type: text/html; charset=utf-8"));
            let body = response
                .split_once("\r\n\r\n")
                .expect("headers should be separated from the body")
                .1;
            assert!(
                body.contains("frontend") && body.contains("/api/state"),
                "placeholder should explain the missing frontend, got: {body}"
            );
        } else {
            // dist/ was embedded: the root serves the entry point.
            assert!(response.contains("Content-Type: text/html"));
        }
    }

    #[test]
    fn non_get_requests_are_rejected() {
        let addr = spawn_test_server();
        let response = send_request(
            addr,
            "POST /api/state HTTP/1.1\r\nHost: localhost\r\nContent-Length: 2\r\nConnection: close\r\n\r\n{}",
        );
        assert!(
            response.starts_with("HTTP/1.1 405 Method Not Allowed\r\n"),
            "got: {response}"
        );
    }

    #[test]
    fn port_from_env_reads_pc_ai_port() {
        // Env vars are process-global: serialize against any other test that
        // might read this variable.
        static ENV_LOCK: Mutex<()> = Mutex::new(());
        let _guard = ENV_LOCK.lock();

        std::env::set_var("PC_AI_PORT", "9123");
        assert_eq!(port_from_env(), 9123);

        std::env::set_var("PC_AI_PORT", "not-a-port");
        assert_eq!(port_from_env(), DEFAULT_PORT, "invalid value falls back");

        std::env::set_var("PC_AI_PORT", "0");
        assert_eq!(port_from_env(), DEFAULT_PORT, "port 0 is not a valid choice");

        std::env::remove_var("PC_AI_PORT");
        assert_eq!(port_from_env(), DEFAULT_PORT);
    }
}
